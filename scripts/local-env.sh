#!/bin/sh
# Writes .env for the LOCAL Supabase stack (dev server, `vite preview`, E2E, CI), from
# `npx supabase status`. Refuses to overwrite an existing .env unless given --force.
# Never use this for staging or production: their values live in Netlify.
set -eu

if [ -f .env ] && [ "${1:-}" != "--force" ]; then
	echo ".env already exists; run with --force to replace it." >&2
	exit 0
fi

status=$(npx supabase status -o json 2>/dev/null)
node -e '
const text = process.argv[1];
const s = JSON.parse(text.slice(text.indexOf("{")));
const host = new URL(s.API_URL).hostname;
if (host !== "127.0.0.1" && host !== "localhost") {
	console.error(`Refusing to write .env for a non-local Supabase: ${host}`);
	process.exit(1);
}
const secret = require("node:crypto").randomBytes(32).toString("base64url");
const lines = [
	"# Generated by scripts/local-env.sh for the local Supabase stack. Do not commit.",
	`SUPABASE_URL=${s.API_URL}`,
	`SUPABASE_PUBLISHABLE_KEY=${s.PUBLISHABLE_KEY}`,
	`SUPABASE_SECRET_KEY=${s.SECRET_KEY}`,
	`RATE_LIMIT_HMAC_SECRET=${secret}`,
	// Feedback email goes to the local Mailpit (smtp_port in supabase/config.toml).
	"SMTP_HOST=127.0.0.1",
	"SMTP_PORT=54325",
	"FEEDBACK_TO=feedback@example.com",
	""
];
require("node:fs").writeFileSync(".env", lines.join("\n"), { mode: 0o600 });
console.log("Wrote .env for the local Supabase stack.");
' "$status"
