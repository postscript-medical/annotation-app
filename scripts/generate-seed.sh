#!/usr/bin/env bash
# Builds supabase/seed.sql for the LOCAL stack (step 0.7 of docs/migration-execution-plan.md):
#   1. a data-only dump of the catalogue tables from the linked project (staging), read-only;
#   2. the local test users from scripts/seed-test-users.sql.
#
# The catalogue holds no personal data. Every other table is excluded from the dump.
# Needs Docker running (the CLI runs pg_dump in a container) and `supabase link` to staging.
# The CLI may ask for the staging database password: type it yourself, never paste it in chat.
#
# Usage: scripts/generate-seed.sh
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

expected_ref="vqwulukmgqifavsvtwcp" # staging
linked_ref="$(cat supabase/.temp/project-ref 2>/dev/null || true)"
if [[ "$linked_ref" != "$expected_ref" ]]; then
  echo "Refusing to dump: linked project is '${linked_ref:-none}', expected staging ($expected_ref)." >&2
  exit 1
fi

# Every public table except the five catalogue tables.
excluded=(
  illustration_raw migration_failures organization_raw organizations product_prices
  products_raw products restricted_organization_specialties specialty_raw sub_specialty_raw
  subscription_plan_products subscription_plans_raw subscription_plans team_raw teams
  user_app_state_raw user_app_states user_raw users
)
exclude_arg="$(printf 'public.%s,' "${excluded[@]}")"
exclude_arg="${exclude_arg%,}"

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

npx supabase db dump --remote --data-only --schema public -x "$exclude_arg" -f "$tmp"

# Fail loudly if anything other than the catalogue tables ended up in the dump.
allowed='^(specialties|sub_specialties|specialty_sub_specialties|illustrations|sub_specialty_illustrations)$'
unexpected="$(grep -oE '^(INSERT INTO|COPY) "?public"?\."?[a-z_]+' "$tmp" \
  | sed -E 's/.*\."?//' | sort -u | grep -vE "$allowed" || true)"
if [[ -n "$unexpected" ]]; then
  echo "Dump contains non-catalogue tables, not writing seed.sql:" >&2
  echo "$unexpected" >&2
  exit 1
fi

{
  echo "-- GENERATED by scripts/generate-seed.sh on $(date -u +%Y-%m-%d). Do not edit by hand."
  echo "-- Local stack only: runs on \`supabase db reset\`, never on a hosted project."
  echo
  echo "-- Catalogue, dumped from staging ($expected_ref)."
  cat "$tmp"
  echo
  cat scripts/seed-test-users.sql
} > supabase/seed.sql

echo "Wrote supabase/seed.sql"
